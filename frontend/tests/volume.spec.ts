import {test,expect} from '@playwright/test';
import fs from 'node:fs';
test.use({launchOptions:{args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']}});
test('existing real case: MPR, paired 3D rotation and fused CT-PET opacity',async({page,request})=>{
  test.setTimeout(180000);
  const saved=JSON.parse(fs.readFileSync('../data/qa/mixed_case_session.json','utf8'));
  const api=process.env.E2E_API_URL||'http://127.0.0.1:8108/api';
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')console.log('BROWSER:',m.text());});
  await page.addInitScript(({token})=>{sessionStorage.setItem('pet-demo-session',token);localStorage.setItem('pet-demo-guest-session',token);},{token:saved.token});
  await page.goto(`/?job=${saved.id}`);
  await expect(page.getByRole('heading',{name:'Ảnh PET đã sẵn sàng.'})).toBeVisible();
  await expect(page.locator('.mpr-section')).toHaveAttribute('data-ready','true',{timeout:60000});
  await expect(page.locator('.mpr-panel canvas')).toHaveCount(9);
  await page.getByRole('button',{name:'Xem 3D',exact:true}).click();
  await expect(page.locator('.volume-grid')).toHaveAttribute('data-ready','true',{timeout:90000});
  await expect(page.locator('.volume-canvas canvas')).toHaveCount(2);
  await expect(page.getByLabel('Hiển thị CT')).toHaveValue('body');
  await page.getByRole('button',{name:'Xoay phải',exact:false}).click();
  await page.getByRole('button',{name:'Đặt lại góc nhìn'}).click();
  await page.screenshot({path:'../artifacts/screenshots/paired-3d.png',fullPage:true});
  await page.locator('.volume-canvas').evaluateAll(elements=>elements.forEach(el=>el.addEventListener('CORNERSTONE_CAMERA_MODIFIED',((event:CustomEvent)=>{(el as HTMLElement).dataset.camera=JSON.stringify(event.detail.camera);}) as EventListener)));
  await page.locator('.volume-canvas').first().scrollIntoViewIfNeeded();
  await page.locator('.volume-canvas').first().evaluate(el=>el.scrollIntoView({block:'center'}));
  const before=await page.locator('.volume-canvas').first().screenshot();
  const box=(await page.locator('.volume-canvas').first().boundingBox())!;
  await page.mouse.move(box.x+box.width*.4,box.y+box.height*.5);await page.mouse.down();
  await page.mouse.move(box.x+box.width*.65,box.y+box.height*.6,{steps:12});await page.mouse.up();
  await expect.poll(async()=>Buffer.compare(before,await page.locator('.volume-canvas').first().screenshot()),{timeout:60000}).not.toBe(0);
  await expect.poll(()=>page.locator('.volume-canvas').evaluateAll(elements=>{const cameras=elements.map(el=>(el as HTMLElement).dataset.camera);return !!cameras[0]&&cameras[0]===cameras[1];})).toBeTruthy();
  const fixed=await page.locator('.volume-canvas').first().screenshot();
  await page.getByRole('button',{name:'Xoay tự động',exact:true}).click();
  await expect.poll(async()=>Buffer.compare(fixed,await page.locator('.volume-canvas').first().screenshot()),{timeout:60000}).not.toBe(0);
  await page.getByRole('button',{name:'Dừng xoay',exact:true}).click();
  await page.getByLabel('Hiển thị CT').selectOption('bone');
  await page.getByLabel('Hiển thị CT').selectOption('body');
  await page.mouse.wheel(0,120);await page.getByRole('button',{name:'Đặt lại góc nhìn'}).click();
  await page.getByRole('button',{name:'Chồng CT–PET',exact:true}).click();
  await expect(page.locator('.volume-grid')).toHaveAttribute('data-ready','true',{timeout:90000});
  await expect(page.locator('.volume-canvas canvas')).toHaveCount(1);
  const overlay=await page.locator('.volume-canvas').screenshot();
  await page.getByLabel('Độ đậm PET',{exact:true}).fill('0');
  await expect.poll(async()=>Buffer.compare(overlay,await page.locator('.volume-canvas').screenshot())).not.toBe(0);
  await page.getByLabel('Độ đậm PET',{exact:true}).fill('0.8');
  await page.screenshot({path:'../artifacts/screenshots/fusion-3d.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.screenshot({path:'../artifacts/screenshots/fusion-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'MPR liên kết',exact:true}).click();
  await expect(page.locator('.mpr-section')).toHaveAttribute('data-ready','true',{timeout:60000});
  await expect(page.locator('.mpr-panel canvas')).toHaveCount(9);
  expect((await request.get(`${api}/jobs/${saved.id}/volume/ct`)).status()).toBe(401);
  const guest=(await (await request.post(`${api}/auth/guest`)).json()).access_token;
  expect((await request.get(`${api}/jobs/${saved.id}/volume/pet`,{headers:{Authorization:`Bearer ${guest}`}})).status()).toBe(404);
  expect(errors).toEqual([]);
});


test('WebGL2 unavailable: explain fallback and keep MPR usable',async({page})=>{
  const saved=JSON.parse(fs.readFileSync('../data/qa/mixed_case_session.json','utf8'));
  await page.addInitScript(({token})=>{sessionStorage.setItem('pet-demo-session',token);localStorage.setItem('pet-demo-guest-session',token);const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(kind:string,...args:any[]){if(kind==='webgl2')return null;return (original as any).call(this,kind,...args);} as typeof original;},{token:saved.token});
  await page.goto(`/?job=${saved.id}`);
  await expect(page.getByRole('heading',{name:'Ảnh PET đã sẵn sàng.'})).toBeVisible();
  await page.getByRole('button',{name:'Xem 3D',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('chưa hỗ trợ WebGL2');
  await page.getByRole('button',{name:'MPR liên kết',exact:true}).click();
  await expect(page.locator('.mpr-section')).toHaveAttribute('data-ready','true',{timeout:60000});
  await expect(page.locator('.mpr-panel canvas')).toHaveCount(9);
});

test('linked MPR: crosshair, physical coordinates, windowing and fusion',async({page})=>{
  const saved=JSON.parse(fs.readFileSync('../data/qa/mixed_case_session.json','utf8'));
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(({token})=>{sessionStorage.setItem('pet-demo-session',token);localStorage.setItem('pet-demo-guest-session',token);},{token:saved.token});
  await page.goto(`/?job=${saved.id}`);
  await page.getByRole('button',{name:'MPR liên kết',exact:true}).click();
  await expect(page.locator('.mpr-section')).toHaveAttribute('data-ready','true',{timeout:60000});
  await expect(page.locator('.mpr-panel canvas')).toHaveCount(9);
  await expect(page.locator('.mpr-probe')).toContainText('HU');
  const original=await page.locator('.mpr-probe').innerText();
  await page.getByLabel('Axial CT',{exact:true}).click({position:{x:100,y:110}});
  await expect(page.locator('.mpr-probe')).not.toHaveText(original);
  const linked=await page.locator('.mpr-probe').innerText();
  await page.getByLabel('Axial PET',{exact:true}).click({position:{x:100,y:110}});
  await expect(page.locator('.mpr-probe')).toHaveText(linked);
  const before=await page.getByLabel('Axial CT',{exact:true}).screenshot();
  await page.getByLabel('Cửa sổ MPR',{exact:true}).selectOption('lung');
  expect(Buffer.compare(before,await page.getByLabel('Axial CT',{exact:true}).screenshot())).not.toBe(0);
  await page.getByLabel('Độ đậm PET MPR',{exact:true}).fill('0');
  await expect.poll(()=>page.locator('.mpr-panel canvas').evaluateAll(elements=>{const [ct,,fusion]=elements as HTMLCanvasElement[];return ct.toDataURL()===fusion.toDataURL();})).toBeTruthy();
  await page.getByLabel('Độ đậm PET MPR',{exact:true}).fill('0.6');
  await page.screenshot({path:'../artifacts/screenshots/linked-mpr.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  expect(errors).toEqual([]);
});
